import test from 'node:test';
import assert from 'node:assert/strict';
import {initialState} from '../src/core/gameState.js';
import {battleEnergyRewards,getWildPokemon} from '../src/core/wildData.js';
import {calculateBattleEnergyRewards} from '../src/core/combatEngine.js';
import {initialEconomy,unlockNextLayer,purchaseWithEnergy,grantBattleEnergy,movePlanet,tickEconomy} from '../src/core/energySystem.js';
import {encodeSave,decodeSave,SAVE_VERSION} from '../src/core/saveCodec.js';
test('normal reward always and conditional ten percent extras, no duplicate normal',()=>{
 const fire=getWildPokemon('charmander'),pika=getWildPokemon('pikachu'),bird=getWildPokemon('pidgey'),lotad=getWildPokemon('lotad');
 assert.deepEqual(battleEnergyRewards(fire,0,{unlockedLayer:1}),{노말:28});
 assert.deepEqual(battleEnergyRewards(fire,0,{unlockedLayer:2}),{노말:28,불꽃:28*0.1});
 assert.deepEqual(battleEnergyRewards(pika,0,{unlockedLayer:2}),{노말:35});
 assert.deepEqual(battleEnergyRewards(pika,0,{unlockedLayer:3}),{노말:35,전기:3.5});
 assert.deepEqual(battleEnergyRewards(bird,0,{unlockedLayer:4}),{노말:2,비행:0.2});
 const rewards=battleEnergyRewards(lotad,1,{unlockedLayer:2});
 assert.equal(rewards.노말,635);
 assert.ok(Math.abs(Number(rewards.물)-63.5)<1e-9);
 assert.ok(Math.abs(Number(rewards.풀)-63.5)<1e-9);
});
test('SU011 amplifies only normal, honey applies once to all rewards',()=>{
 const s=initialState();
 const state={...s,unlockedLayer:2,permanentUpgrades:{SU011:10},dittoStats:{...s.dittoStats,honey:100}};
 const rewards=calculateBattleEnergyRewards(state,getWildPokemon('charmander'),0);
 assert.ok(Math.abs(Number(rewards.노말)-61.6)<1e-9);
 assert.ok(Math.abs(Number(rewards.불꽃)-3.08)<1e-9);
});
test('milestone production does not unlock layers; locked currency cannot be spent or earned',()=>{
 let s=initialEconomy();
 s=grantBattleEnergy(s,['노말','불꽃'],1025);
 assert.equal(s.energyBalances.불꽃,0);
 s=purchaseWithEnergy(s,{노말:1025});
 assert.equal(s.particleMilestones.노말,1);
 assert.equal(s.unlockedLayer,1);
 assert.equal(tickEconomy(s,1).unlockedLayer,1);
 const forged={...s,energyBalances:{...s.energyBalances,불꽃:10}};
 assert.equal(purchaseWithEnergy(forged,{불꽃:1}),forged);
 assert.equal(unlockNextLayer(s,3),s);
 s=unlockNextLayer(s,2);
 assert.equal(s.unlockedLayer,2);
 assert.equal(unlockNextLayer(s,2),s);
 s=grantBattleEnergy(s,['불꽃'],1025);
 s=purchaseWithEnergy(s,{불꽃:1025});
 assert.equal(s.particleMilestones.불꽃,1);
 assert.equal(s.unlockedLayer,2);
 assert.equal('particleBank' in s,false);
 s=movePlanet({...s,pendingStellar:1});
 assert.equal(s.unlockedLayer,2);
 assert.equal(s.particleMilestones.노말,1);
 assert.equal(s.particleMilestones.불꽃,0);
 assert.equal(s.particleBalances.불꽃,0);
 assert.equal(s.stellar,1);
});
test('v18 saves retain unlocked layer and omit bank',()=>{
 const state={...initialState(),unlockedLayer:4};
 const saved=decodeSave(encodeSave(state)).game;
 assert.equal(SAVE_VERSION,18);
 assert.equal(saved.unlockedLayer,4);
 assert.equal('particleBank' in saved,false);
});
